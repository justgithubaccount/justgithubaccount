#!/usr/bin/env python3
"""Build the profile and static website without network, credentials or dependencies."""
import argparse
import datetime
import hashlib
from html import escape as h
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import art

ROOT = Path(__file__).resolve().parents[1]
SITE_URL = 'https://justgithubaccount.github.io/'
PROFILE_URL = 'https://github.com/justgithubaccount'
SOURCES = {
    'k8s': ('justgithubaccount/app-poly-gitops-k8s', {'README.md', 'clusters/dev/kustomization.yaml', 'clusters/smoke/kustomization.yaml'}),
    'infra': ('justgithubaccount/app-poly-gitops-infra', {'README.md', 'terraform/timeweb/main.tf', '.github/workflows/timeweb-smoke.yaml'}),
    'fastapi': ('justgithubaccount/app-poly-gitops-fastapi', {'README.md', 'app/api.py', 'app/core/llm_client.py'}),
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def keys(obj, expected):
    require(isinstance(obj, dict) and set(obj) == set(expected.split()), 'Unexpected manifest fields')


def plain(value, maximum=500):
    require(isinstance(value, str) and 1 <= len(value) <= maximum, 'Invalid text length')
    require(value == value.strip() and not re.search(r'[\x00-\x1f\x7f<>\[\]`|\\{}]', value), 'Only plain public text is allowed')
    require(not re.search(r'https?:|mailto:|www\.|@', value, re.I), 'Links and contacts require separate review')


def validate(data):
    keys(data, 'schema_version reviewed_on publication_state identity projects')
    require(data['schema_version'] == 'public-portfolio.v1', 'Unknown schema')
    require(data['publication_state'] in ('DRAFT', 'RELEASE_APPROVED'), 'Unsupported publication state')
    require(isinstance(data['reviewed_on'], str) and re.fullmatch(r'\d{4}-\d{2}-\d{2}', data['reviewed_on']), 'Invalid review date')
    datetime.date.fromisoformat(data['reviewed_on'])
    keys(data['identity'], 'handle name headline intro focus_title focus_intro')
    require(data['identity']['handle'] == 'justgithubaccount', 'Wrong identity')
    for key, value in data['identity'].items():
        plain(value, 60 if key in ('handle', 'name', 'headline', 'focus_title') else 400)
    require(len(data['identity']['headline'].split('. ')) == 3, 'Headline must have three short sentences')
    require(all(len(line) <= 18 for line in data['identity']['headline'].split('. ')), 'Headline line exceeds vector layout budget')
    projects = data['projects']
    require(isinstance(projects, list) and len(projects) == 3, 'Exactly three reviewed projects are required')
    require([p.get('id') for p in projects if isinstance(p, dict)] == list(SOURCES), 'Project allowlist/order mismatch')
    for p in projects:
        keys(p, 'id repository revision visibility license title category problem description boundary tags evidence focus focus_detail')
        repo, paths = SOURCES[p['id']]
        require(p['repository'] == repo, 'Repository outside public allowlist')
        require(isinstance(p['revision'], str) and re.fullmatch('[0-9a-f]{40}', p['revision']), 'An exact commit SHA is required')
        require(p['visibility'] == 'PUBLIC' and p['license'] == 'MIT', 'Unreviewed public source metadata')
        require(isinstance(p['evidence'], list) and all(isinstance(x, str) for x in p['evidence']) and len(p['evidence']) == len(paths) and set(p['evidence']) == paths, 'Evidence path outside allowlist')
        for key in ('title', 'category', 'problem', 'description', 'boundary', 'focus', 'focus_detail'):
            plain(p[key], 45 if key in ('title', 'category', 'focus') else 400)
        require(isinstance(p['tags'], list) and len(p['tags']) == 3, 'Three technology labels required')
        for tag in p['tags']:
            plain(tag, 24)
    return data


def repo_url(p):
    return 'https://github.com/' + p['repository']


def evidence_url(p, path):
    return repo_url(p) + '/blob/' + p['revision'] + '/' + path


def readme(d):
    i = d['identity']
    out = [f'<!-- Generated by scripts/build.py. Edit data/public-portfolio.json. -->\n\n<picture>\n  <source media="(max-width: 600px)" srcset="assets/hero-compact.svg"/>\n  <img src="assets/hero.svg" alt="{h(i["headline"])} {h(i["name"])}: Python APIs, cloud infrastructure and GitOps."/>\n</picture>\n',
           f'# Hi, I’m {i["name"]}.\n\n{i["intro"]}\n']
    if d['publication_state'] == 'RELEASE_APPROVED':
        out.append(f'[Explore the portfolio]({SITE_URL}) · [Browse my GitHub]({PROFILE_URL})\n')
    else:
        out.append('[Portfolio website — publication pending](site/index.html) · [Browse my GitHub](https://github.com/justgithubaccount)\n')
    out.append('## Selected public projects\n\nThree parts of one engineering lab: application, infrastructure and delivery.\n')
    for n, p in enumerate(d['projects'], 1):
        out.append(f'<a href="{repo_url(p)}">\n  <picture>\n    <source media="(max-width: 600px)" srcset="assets/project-{p["id"]}-compact.svg"/>\n    <img src="assets/project-{p["id"]}.svg" alt="{h(p["category"])}: {h(p["title"])} {h(", ".join(p["tags"]))}."/>\n  </picture>\n</a>\n\n{p["description"]}\n\n{p["boundary"]}\n\n[Read the source]({evidence_url(p, "README.md")}) · Revision `{p["revision"][:12]}`\n')
    out.append(f'## Engineering focus\n\n{i["focus_intro"]}\n')
    for p in d['projects']:
        out.append(f'- **{p["focus"]}.** {p["focus_detail"]}')
    out.append('\nThese are public code projects. Explore the repositories for setup requirements and implementation detail.\n')
    return '\n'.join(out)


def structured(d):
    return {
        '@context': 'https://schema.org',
        '@graph': [
            {'@type': 'Person', '@id': SITE_URL + '#author', 'name': d['identity']['name'], 'alternateName': d['identity']['handle'], 'sameAs': [PROFILE_URL]},
            {'@type': 'CollectionPage', '@id': SITE_URL, 'name': d['identity']['headline'], 'description': d['identity']['intro'],
             'author': {'@id': SITE_URL + '#author'}, 'inLanguage': 'en',
             'hasPart': [{'@type': 'SoftwareSourceCode', 'name': p['category'], 'description': p['description'], 'codeRepository': repo_url(p), 'version': p['revision'], 'url': evidence_url(p, 'README.md')} for p in d['projects']]}
        ]}


def website(d):
    i = d['identity']
    project_html = []
    for n, p in enumerate(d['projects'], 1):
        links = ''.join(f'<li><a href="{evidence_url(p, path)}">{h(path)}</a></li>' for path in p['evidence'])
        project_html.append(f'''<article class="project" id="{p['id']}">
<div class="project-art"><img src="assets/art-{p['id']}.svg" alt="" width="600" height="640" loading="lazy"/></div>
<div class="project-copy"><p class="project-category"><span>0{n}</span> {h(p['category'])}</p>
<h3>{h(p['title'])}</h3><p class="question">{h(p['problem'])}</p><p>{h(p['description'])}</p>
<ul class="tags" aria-label="Technologies">{''.join(f'<li>{h(t)}</li>' for t in p['tags'])}</ul>
<a class="text-link" href="{repo_url(p)}">Explore {h(p['category'].lower())} <span aria-hidden="true">↗</span></a>
<details><summary>Source evidence &amp; project scope</summary><p>{h(p['boundary'])}</p><p>Public source snapshot: <code>{p['revision'][:12]}</code></p><ul class="evidence">{links}</ul></details></div>
</article>''')
    focus = ''.join(f'<li><span class="focus-number">0{n}</span><h3>{h(p["focus"])}</h3><p>{h(p["focus_detail"])}</p><a href="#{p["id"]}">See the project <span aria-hidden="true">↗</span></a></li>' for n, p in enumerate(d['projects'], 1))
    template = (ROOT / 'templates/index.html').read_text(encoding='utf-8')
    values = {'title': h(i['headline'] + ' — ' + i['name']), 'description': h(i['intro']), 'name': h(i['name']),
              'hero_lines': '<br/>'.join(h(line.rstrip('.') + '.') if n < 2 else '<span>' + h(line.rstrip('.') + '.') + '</span>' for n, line in enumerate(i['headline'].split('. '))),
              'intro': h(i['intro']), 'projects': '\n'.join(project_html), 'focus': focus,
              'focus_title': h(i['focus_title']), 'focus_intro': h(i['focus_intro']),
              'robots': 'index, follow' if d['publication_state'] == 'RELEASE_APPROVED' else 'noindex, nofollow',
              'json_ld': json.dumps(structured(d), ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')}
    # Substitute once: manifest text cannot become a template instruction.
    return re.sub(r'\{\{(\w+)\}\}', lambda m: values[m[1]], template)


def json_text(value):
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + '\n'


def render(data):
    d = validate(data)
    files = {'README.md': readme(d), 'assets/hero.svg': art.hero(d), 'assets/hero-compact.svg': art.compact_hero(d)}
    for n, p in enumerate(d['projects'], 1):
        files[f'assets/project-{p["id"]}.svg'] = art.card(p, n)
        files[f'assets/project-{p["id"]}-compact.svg'] = art.compact_card(p, n)
    files['site/index.html'] = website(d)
    files['site/styles.css'] = (ROOT / 'templates/styles.css').read_text(encoding='utf-8')
    files['site/assets/orbital.svg'] = art.artwork('hero', 'Braided orbital field')
    for p in d['projects']:
        files[f'site/assets/art-{p["id"]}.svg'] = art.artwork(p['id'], p['category'])
    files['site/assets/favicon.svg'] = art.shell(64, 64, 'Connected', 'Two connected violet and cyan orbits.', '<rect width="64" height="64" rx="16" fill="#080c1c"/><ellipse cx="32" cy="32" rx="23" ry="11" transform="rotate(-45 32 32)" fill="none" stroke="url(#strand)" stroke-width="3"/><ellipse cx="32" cy="32" rx="23" ry="11" transform="rotate(45 32 32)" fill="none" stroke="url(#strand)" stroke-width="3"/>')
    rule = 'Allow: /' if d['publication_state'] == 'RELEASE_APPROVED' else 'Disallow: /'
    files['site/robots.txt'] = f'User-agent: *\n{rule}\n\nSitemap: {SITE_URL}sitemap.xml\n'
    files['site/sitemap.xml'] = f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>{SITE_URL}</loc></url></urlset>\n'
    files['site/structured-data.json'] = json_text(structured(d))
    llms = [f'# {d["identity"]["name"]} / justgithubaccount\n', f'> {d["identity"]["intro"]}\n', 'Public code projects in an engineering lab. Repository snapshots describe code, not a live hosted service.\n', '## Public projects\n']
    for p in d['projects']:
        llms.append(f'- [{p["category"]}]({evidence_url(p, "README.md")}): {p["description"]} Revision: {p["revision"]}.')
    files['site/llms.txt'] = '\n'.join(llms) + '\n'
    files['site/.nojekyll'] = ''
    info = {
        'schema_version': 'portfolio-export.v1', 'publication_state': d['publication_state'],
        'manifest_sha256': hashlib.sha256(json_text(d).encode()).hexdigest(),
        'generator_sha256': hashlib.sha256(b''.join((ROOT / p).read_bytes() for p in ['scripts/build.py', 'scripts/art.py', 'templates/index.html', 'templates/styles.css'])).hexdigest(),
        'files': {name[5:]: hashlib.sha256(body.encode()).hexdigest() for name, body in files.items() if name.startswith('site/')},
    }
    files['site/build-info.json'] = json_text(info)
    return files


def build(data, out):
    files = render(data)  # Validate the entire input before the first write.
    for name, body in files.items():
        dest = out / name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(body, encoding='utf-8', newline='\n')
    return files


def check(data, out):
    files = render(data)
    bad = [name for name, body in files.items() if not (out / name).is_file() or (out / name).read_bytes() != body.encode()]
    for directory in ('assets', 'site'):
        if (out / directory).exists():
            bad.extend(str(p.relative_to(out)) for p in (out / directory).rglob('*') if p.is_file() and str(p.relative_to(out)) not in files)
    return sorted(set(bad))


def export_pages(data, out):
    files = render(data)
    for name, body in files.items():
        if name.startswith('site/'):
            dest = out / name[5:]
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(body, encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, default=ROOT / 'data/public-portfolio.json')
    parser.add_argument('--out', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true', help='Read only; fail on missing, changed or stale generated files')
    parser.add_argument('--pages-dir', type=Path, help='Export the exact website bytes to a separate local directory')
    args = parser.parse_args()
    try:
        data = json.loads(args.manifest.read_text(encoding='utf-8'))
        if args.check:
            require(args.pages_dir is None, '--check cannot write a Pages export')
            bad = check(data, args.out)
            if bad:
                print('Generated output drift: ' + ', '.join(bad), file=sys.stderr)
                return 1
            print('Generated output: reproducible')
        else:
            build(data, args.out)
            if args.pages_dir:
                export_pages(data, args.pages_dir)
            print('Generated profile, SVG assets and static website')
    except (ValueError, OSError) as exc:
        print(f'Build failed: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
